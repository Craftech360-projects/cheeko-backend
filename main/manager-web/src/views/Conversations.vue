          <div class="kpi-label">AI talk time</div>
        </div>
        <div class="card kpi">
          <div class="kpi-value">{{ kpis.talkSessions }}
            <span v-if="deltas.talkSessions !== null && deltas.talkSessions !== undefined" class="kpi-delta" :class="deltas.talkSessions >= 0 ? 'good' : 'bad'">
              {{ deltas.talkSessions >= 0 ? '▲' : '▼' }}{{ Math.abs(deltas.talkSessions) }}%
