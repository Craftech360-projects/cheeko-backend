  <div class="conversations-page">
    <div class="page-head">
      <div>
        <h1 class="page-title">Conversations</h1>
        <p class="page-subtitle">What kids talk about, with summarised sessions · first names only</p>
      </div>
      <el-radio-group v-model="range" size="small" @change="load">
        <el-radio-button label="7d">7 days</el-radio-button>
        <el-radio-button label="30d">30 days</el-radio-button>
      </el-radio-group>
    </div>

    <div v-loading="loading">
      <!-- KPI row -->
      <div class="kpi-row">
