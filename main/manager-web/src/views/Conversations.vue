      <!-- Session feed + transcript -->
      <div class="feed-grid">
        <div class="card feed">
          <h4 class="card-subtitle">Sessions</h4>
          <div v-if="summaries.length" class="session-list">
            <div v-for="s in summaries" :key="s.id"
              class="session-row" :class="{ selected: selectedId === s.id }"
              @click="openTranscript(s)">
              <div class="session-main">
                <span class="session-headline">{{ s.headline || s.summary }}</span>
                <span class="session-meta mono">{{ s.macAddress }} · {{ s.turns }} turns · {{ shortDate(s.updatedAt) }}</span>
              </div>
              <div class="session-tags" v-if="s.tags && s.tags.length">
                <span v-for="tag in s.tags.slice(0, 3)" :key="tag" class="mini-tag">{{ tag }}</span>
              </div>
            </div>
          </div>
          <div v-else class="card-empty">No conversations summarised in this period.</div>
        </div>

        <div class="card transcript" v-loading="transcriptLoading">
          <h4 class="card-subtitle">Transcript</h4>
          <template v-if="transcript">
            <p class="transcript-headline">{{ transcript.headline }}</p>
            <div class="transcript-lines">
              <div v-for="(line, i) in transcript.lines" :key="i" class="line" :class="line.role === 'assistant' ? 'agent' : 'kid'">
                <span class="line-speaker">{{ line.speaker }}</span>
                <span class="line-text">{{ line.text }}</span>
              </div>
            </div>
          </template>
          <div v-else class="card-empty">Select a session to read its transcript.</div>
        </div>
      </div>
    </div>
  </div>
</template>

<script>
import Api from '@/apis/api';

export default {
  name: 'Conversations',
  data() {
    return {
      range: '7d',
      loading: false,
      kpis: {},
      deltas: {},
      topics: [],
      summaries: [],
      transcript: null,
      transcriptLoading: false,
      selectedId: null
    };
  },
  created() {
    this.load();
  },
  methods: {
    formatNumber(v) {
      return Number(v).toLocaleString('en-IN');
    },
    shortDate(value) {
      if (!value) return '—';
      return new Date(value).toLocaleString('en-IN', { day: 'numeric', month: 'short', hour: '2-digit', minute: '2-digit' });
    },
    load() {
      this.loading = true;
      this.transcript = null;
      this.selectedId = null;
      Api.admin.getFounderConversations(this.range, ({ data }) => {
        this.loading = false;
        if (data.code === 0 && data.data) {
          this.kpis = data.data.kpis || {};
          this.deltas = data.data.deltas || {};
          this.topics = (data.data.sections && data.data.sections.topics) || [];
          this.summaries = (data.data.sections && data.data.sections.summaries) || [];
        } else {
          this.$message.error(data.msg || 'Failed to load conversations');
        }
      });
    },
    openTranscript(session) {
      this.selectedId = session.id;
      this.transcriptLoading = true;
      Api.admin.getConversationTranscript(session.sessionId, ({ data }) => {
        this.transcriptLoading = false;
        if (data.code === 0 && data.data) {
          this.transcript = data.data;
        } else {
          this.$message.error(data.msg || 'Failed to load transcript');
        }
      });
    }
  }
}
</script>

